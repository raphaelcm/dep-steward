/**
 * The regeneration, run end to end the way GitHub would run it.
 *
 * Runsense-ai/runsense#3034: a group bump took prisma from 7.10.0 to 7.10.1.
 * Runsense commits its generated Prisma client, so CI's sync check went red,
 * and the fix was `npm run db:generate` with a placeholder DATABASE_URL: two
 * files, twelve lines, every one a version string. Autofix escalated it: its
 * agent has no generator to run, and the bounds' ten-line budget would have
 * refused the output anyway.
 *
 * Installed with --regenerate, the review workflow's regenerate jobs re-run
 * the generator on pull_request (where the bump's code may run) and leave a
 * verdict artifact. When CI fails, autofix reads that verdict as data and,
 * when it is verified, hands the regeneration to the push job, which reads it
 * again for itself and pushes it as the Claude GitHub App. No agent runs.
 *
 * Everything here runs the rendered jobs (test/lib/actions-sim.mjs): the two
 * pull_request jobs in fresh checkouts with an `npm` whose `run db:generate`
 * is a stand-in generator, the artifacts through a local store, then the two
 * workflow_run jobs against a `gh` that answers GitHub's REST routes from
 * that store, and a real git remote that records who pushed.
 */

const REPO = dirname(dirname(fileURLToPath(import.meta.url)));
const HEAD_BRANCH = 'dependabot/npm_and_yarn/npm-minor-patch-116ae265fb';
const REVIEW_RUN = 777;
const REGEN_FLAGS = [
  '--regenerate', 'npm run db:generate',
  '--regenerate-path', 'src/generated/prisma',
  '--regenerate-env', 'DATABASE_URL=postgresql://runsense:runsense@localhost:5432/runsense',
];

function render(flags = REGEN_FLAGS) {
  const fakeRepo = mkdtempSync(join(tmpdir(), 'ds-rg-repo-'));
  writeFileSync(join(fakeRepo, 'package.json'), '{"name":"app"}\n');
  writeFileSync(join(fakeRepo, 'package-lock.json'), '{}\n');
  const out = mkdtempSync(join(tmpdir(), 'ds-rg-out-'));
  execFileSync(
    'sh',
    [join(REPO, 'plugin', 'install.sh'), '--render-only', '--out', out, '--ci-name', 'CI', '--assignee', 'octocat', ...flags],
    { cwd: fakeRepo, env: { ...process.env, DEP_STEWARD_SRC: join(REPO, 'plugin') }, stdio: 'pipe' },
  );
  return out;
}

const RENDERED = render();
const WORKFLOW = readFileSync(join(RENDERED, '.github/workflows/dependabot-review.yml'), 'utf8');
const JOBS = parseJobs(WORKFLOW);

// The stand-in generator: Prisma's client embeds the version that generated
// it, so a version bump changes three lines in each of two files.
const GENERATOR = `#!/usr/bin/env bash
set -eu
v=$(cat node_modules/prisma/VERSION)
case "$v" in 7.10.0) e=0edf323efd1d98336f3f0a68684b56f689b900d3 ;; *) e=9a4b2c1d0e8f7a6b5c4d3e2f1a0b9c8d7e6f5a4b ;; esac
mkdir -p src/generated/prisma/internal src/generated/prisma/models
for f in class prismaNamespace; do
  printf '// Generated by Prisma %s. Do not edit.\\nexport const config = {\\n  "clientVersion": "%s",\\n  "engineVersion": "%s",\\n  "activeProvider": "postgresql",\\n}\\n' "$v" "$v" "$e" > "src/generated/prisma/internal/$f.ts"
done
printf 'export type User = { id: string }\\n' > src/generated/prisma/models/User.ts
case "\${GEN_EXTRA:-}" in
  nondeterministic) date +%s%N > src/generated/prisma/internal/stamp.ts ;;
  outside) echo 'export const timeout = 2000;' > src/client.ts ;;
  lockfile) sed -i 's/"lockfileVersion":3/"lockfileVersion": 3/' package-lock.json ;;
  github) mkdir -p .github/workflows; echo 'name: generated' > .github/workflows/generated.yml ;;
  fails) echo 'Error: the generator crashed' >&2; exit 1 ;;
esac
`;

// `npm ci` installs the lockfile's prisma; `npm run db:generate` is the
// generator, which, like Prisma's config loader, needs DATABASE_URL set.
// Every call is logged with the job that made it.
const NPM_STUB = `#!/usr/bin/env bash
printf '%s\\t%s\\n' "\${DS_JOB:-?}" "$*" >> "$NPM_LOG"
case "$1" in
  ci)
    rm -rf node_modules
    mkdir -p node_modules/prisma
    sed -n 's/.*"node_modules\\/prisma":{"version":"\\([^"]*\\)"}.*/\\1/p' package-lock.json > node_modules/prisma/VERSION ;;
  run)
    [ "$2" = db:generate ] || { echo "npm stub: no script $2" >&2; exit 1; }
    [ -n "\${DATABASE_URL:-}" ] || { echo 'PrismaConfigEnvError: Missing required environment variable: DATABASE_URL' >&2; exit 1; }
    exec bash "$GENERATOR" ;;
  *) echo "npm stub: unexpected $*" >&2; exit 1 ;;
esac
`;

// GitHub's REST routes the workflow_run jobs read, answered from a state file
// and the local artifact store, each run through the caller's own --jq with
// real jq. An unexpected call fails loudly.
const GH_STUB = `#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const args = process.argv.slice(2);
fs.appendFileSync(process.env.GH_LOG, args.join(' ') + '\\n');
const state = JSON.parse(fs.readFileSync(process.env.GH_STATE, 'utf8'));
const flag = (name) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : undefined; };
const fail = (msg) => { process.stderr.write(msg + '\\n'); process.exit(1); };
function out(doc) {
  const text = typeof doc === 'string' ? doc : JSON.stringify(doc);
  const jq = flag('--jq');
  process.stdout.write(jq ? execFileSync('jq', ['-r', jq], { input: text, env: process.env }) : text + '\\n');
  process.exit(0);
}
function count(name) {
  const f = path.join(path.dirname(process.env.GH_STATE), name);
  const n = (fs.existsSync(f) ? Number(fs.readFileSync(f, 'utf8')) : 0) + 1;
  fs.writeFileSync(f, String(n));
  return n;
}
const [a, b] = args;
if (a === 'pr' && b === 'list') out([{ number: 1 }]);
if (a === 'pr' && b === 'view') {
  const what = flag('--json');
  if (what === 'author') out({ author: { login: 'app/dependabot' } });
  if (what === 'commits') out({ commits: state.commits });
  if (what === 'labels') out({ labels: state.labels.map((name) => ({ name })) });
  fail('gh stub: no canned answer for ' + args.join(' '));
}
if (a === 'pr' && b === 'diff') { process.stdout.write(state.bumpPaths.join('\\n') + '\\n'); process.exit(0); }
if (a === 'pr' && b === 'comment') {
  const dir = process.env.GH_COMMENTS;
  fs.writeFileSync(path.join(dir, fs.readdirSync(dir).length + '.md'), flag('--body'));
  process.exit(0);
}
if (a === 'pr' && b === 'edit') process.exit(0);
if (a === 'api') {
  const route = b;
  let m;
  if ((m = /^repos\\/octocat\\/repo\\/actions\\/workflows\\/dependabot-review\\.yml\\/runs\\?event=pull_request&head_sha=([0-9a-f]+)&per_page=20$/.exec(route))) {
    out({ workflow_runs: state.reviewRuns.filter((r) => r.head_sha === m[1]) });
  }
  if ((m = /^repos\\/octocat\\/repo\\/actions\\/workflows\\/4242\\/runs\\?head_sha=([0-9a-f]+)&per_page=100$/.exec(route))) {
    out({ workflow_runs: [{ id: 900, run_attempt: 1, conclusion: 'failure' }] });
  }
  if ((m = /^repos\\/octocat\\/repo\\/actions\\/runs\\/(\\d+)\\/artifacts\\?name=dep-steward-regenerate$/.exec(route))) {
    const polls = count('artifact-polls');
    const dir = path.join(state.store, m[1], 'dep-steward-regenerate');
    const visible = fs.existsSync(dir) && polls > (state.artifactHiddenPolls || 0);
    out({ artifacts: visible ? [{ id: Number(m[1]) * 10 + 1, name: 'dep-steward-regenerate', expired: false, created_at: '2026-10-19T05:01:00Z' }] : [] });
  }
  if ((m = /^repos\\/octocat\\/repo\\/actions\\/runs\\/(\\d+)\\/jobs\\?per_page=100$/.exec(route))) {
    out({ jobs: (state.runs[m[1]] || { jobs: [] }).jobs });
  }
  if ((m = /^repos\\/octocat\\/repo\\/actions\\/runs\\/(\\d+)$/.exec(route))) {
    const polls = count('status-polls');
    const run = state.runs[m[1]] || { status: 'completed' };
    out({ status: polls > (state.statusInProgressPolls || 0) ? run.status : 'in_progress' });
  }
  if ((m = /^repos\\/octocat\\/repo\\/actions\\/artifacts\\/(\\d+)\\/zip$/.exec(route))) {
    const run = String(Math.floor(Number(m[1]) / 10));
    if (state.zip) { process.stdout.write(fs.readFileSync(state.zip)); process.exit(0); }
    const dir = path.join(state.store, run, 'dep-steward-regenerate');
    process.stdout.write(execFileSync('zip', ['-q', '-r', '-', '.'], { cwd: dir }));
    process.exit(0);
  }
}
fail('gh stub: unexpected call: ' + args.join(' '));
`;

const DEPENDABOT_COMMIT = {
  oid: '81252f2277a6cc1ca2d8e12d6b0e2e5f7c9d3a10',
  authors: [{ email: '49699333+dependabot[bot]@users.noreply.github.com', login: 'dependabot[bot]', name: 'dependabot[bot]' }],
};

const lockfile = (v) => `{"name":"app","lockfileVersion":3,"packages":{"node_modules/prisma":{"version":"${v}"}}}\n`;

/**
 * Run the whole regeneration for one Dependabot PR.
 *   bumpTo       the prisma version the bump's lockfile installs ('7.10.0' changes nothing)
 *   extra        what else the generator does: nondeterministic | outside | lockfile | github | fails
 *   review       the review run as GitHub lists it: 'ours' | 'none' | 'other-pr'
 *   inProgress   polls for which the run is still in progress and its verdict not yet listed
 *   zip          ({ headSha, patch }) => a crafted artifact zip, served in place of the store's
 *   forgeDecision  what a turned autofix job hands the push job instead of its own outputs
 *   moveBranch   push a new commit to the PR branch between the two workflow_run jobs
 *   agentEdits   files the fixer agent writes, when it runs
 */
async function runRegeneration({ bumpTo = '7.10.1', extra = '', review = 'ours', inProgress = 0, zip, forgeDecision, moveBranch = false, agentEdits = {} } = {}) {
  const root = mkdtempSync(join(tmpdir(), 'ds-regen-'));
  const d = (...p) => { const x = join(root, ...p); mkdirSync(x, { recursive: true }); return x; };
  const bin = d('bin');
  const store = d('store');
  const comments = d('comments');
  const home = d('home');

  // The PR head as Dependabot left it: the bump's manifests, and the
  // generated client still from 7.10.0, committed with the pipeline's files.
  const seed = d('seed');
  git(['init', '-q', '-b', 'main', seed]);
  git(['config', 'user.email', 'test@example.invalid'], seed);
  git(['config', 'user.name', 'test'], seed);
  writeFileSync(join(seed, '.gitignore'), 'node_modules/\n');
  writeFileSync(join(seed, 'package.json'), '{"name":"app","dependencies":{"prisma":"^7.10.0","vitest":"5.0.3"}}\n');
  writeFileSync(join(seed, 'package-lock.json'), lockfile('7.10.0'));
  mkdirSync(join(seed, 'src'), { recursive: true });
  writeFileSync(join(seed, 'src/client.ts'), 'export const timeout = 1000;\n');
  for (const f of ['.github/dependabot-automerge/autofix-bounds.cjs', '.github/dependabot-automerge/review-lint.cjs', '.github/dependabot-autofix-prompt.md']) {
    mkdirSync(dirname(join(seed, f)), { recursive: true });
    writeFileSync(join(seed, f), readFileSync(join(RENDERED, f), 'utf8'));
  }
  writeFileSync(join(bin, 'generator'), GENERATOR, { mode: 0o755 });
  mkdirSync(join(seed, 'node_modules/prisma'), { recursive: true });
  writeFileSync(join(seed, 'node_modules/prisma/VERSION'), '7.10.0\n');
  execFileSync('bash', [join(bin, 'generator')], { cwd: seed, env: { ...process.env, GEN_EXTRA: '' }, stdio: 'pipe' });
  rmSync(join(seed, 'node_modules'), { recursive: true, force: true });
  git(['add', '-A'], seed);
  git(['commit', '-q', '-m', 'app with its generated client'], seed);
  // The group bump: vitest always moves, prisma when bumpTo says so.
  writeFileSync(join(seed, 'package.json'), `{"name":"app","dependencies":{"prisma":"^${bumpTo}","vitest":"5.0.5"}}\n`);
  writeFileSync(join(seed, 'package-lock.json'), lockfile(bumpTo));
  git(['commit', '-q', '-am', `bump the npm-minor-patch group (prisma ${bumpTo})`], seed);
  const headSha = git(['rev-parse', 'HEAD'], seed).trim();
  const bare = join(d('srv', 'octocat'), 'repo.git');
  git(['init', '-q', '--bare', bare]);
  git(['push', '-q', bare, `HEAD:refs/heads/${HEAD_BRANCH}`], seed);
  const checkout = (name) => {
    const tree = join(root, name);
    git(['clone', '-q', '--branch', HEAD_BRANCH, bare, tree]);
    return tree;
  };

  writeFileSync(join(bin, 'npm'), NPM_STUB, { mode: 0o755 });
  writeFileSync(join(bin, 'gh'), GH_STUB, { mode: 0o755 });
  writeFileSync(join(bin, 'curl'), CURL_STUB, { mode: 0o755 });
  writeFileSync(join(bin, 'sleep'), '#!/bin/sh\nexit 0\n', { mode: 0o755 });
  const log = (n) => { const f = join(bin, n); writeFileSync(f, ''); return f; };
  const npmLog = log('npm.log');
  const ghLog = log('gh.log');
  const curlLog = log('curl.log');
  const ghState = join(bin, 'state.json');

  const calls = { fixer: [], setupNode: [], checkouts: [] };
  const uses = (run) => ({
    'actions/checkout': async ({ with: w }) => { calls.checkouts.push({ ...w }); return { exitCode: 0 }; },
    'actions/setup-node': async ({ with: w }) => { calls.setupNode.push({ ...w }); return { exitCode: 0 }; },
    'actions/upload-artifact': async ({ with: w }) => {
      const dest = join(store, String(run), w.name);
      if (!existsSync(w.path)) return { exitCode: 1, output: `no files at ${w.path}` };
      if (existsSync(dest) && w.overwrite !== 'true') return { exitCode: 1, output: 'an artifact by that name exists' };
      rmSync(dest, { recursive: true, force: true });
      cpSync(w.path, dest, { recursive: true });
      return { exitCode: 0 };
    },
    'actions/download-artifact': async ({ with: w }) => {
      const src = join(store, String(run), w.name);
      if (!existsSync(src)) return { exitCode: 1, output: `no artifact ${w.name}` };
      cpSync(src, w.path, { recursive: true });
      return { exitCode: 0 };
    },
    'anthropics/claude-code-action': async ({ with: w, cwd }) => {
      calls.fixer.push({ ...w });
      for (const [p, content] of Object.entries(agentEdits)) {
        mkdirSync(dirname(join(cwd, p)), { recursive: true });
        writeFileSync(join(cwd, p), content);
      }
      return { exitCode: 0, outputs: { execution_file: '' } };
    },
  });
  const baseEnv = {
    ...process.env,
    ...GIT_ISOLATION,
    PATH: `${bin}:${process.env.PATH}`,
    HOME: home,
    NPM_LOG: npmLog,
    GH_LOG: ghLog,
    GH_STATE: ghState,
    GH_COMMENTS: comments,
    GENERATOR: join(bin, 'generator'),
    GEN_EXTRA: extra,
    CURL_LOG: curlLog,
  };

  // ---- pull_request: the regenerate jobs ----------------------------------
  const prGithub = {
    event_name: 'pull_request',
    repository: 'octocat/repo',
    actor: 'dependabot[bot]',
    event: {
      pull_request: { number: 1, head: { sha: headSha }, user: { login: 'dependabot[bot]' } },
      sender: { login: 'dependabot[bot]', type: 'Bot' },
    },
  };
  const regen = await runJob(JOBS, 'regenerate', {
    github: prGithub, uses: uses(REVIEW_RUN), cwd: checkout('pr-1'),
    env: { ...baseEnv, RUNNER_TEMP: d('rt-1'), DS_JOB: 'regenerate' },
  });
  const verify = await runJob(JOBS, 'regenerate-verify', {
    github: prGithub, uses: uses(REVIEW_RUN), cwd: checkout('pr-2'),
    env: { ...baseEnv, RUNNER_TEMP: d('rt-2'), DS_JOB: 'regenerate-verify' },
    needs: { regenerate: { outputs: regen.outputs, result: regen.failed ? 'failure' : 'success' } },
  });
  const conclusion = (j) => (j.skipped ? 'skipped' : j.failed ? 'failure' : 'success');
  const verdictFile = join(store, String(REVIEW_RUN), 'dep-steward-regenerate', 'verdict');
  const verdict = existsSync(verdictFile) ? readFileSync(verdictFile, 'utf8').trim() : null;

  const reviewRun = {
    id: REVIEW_RUN, head_sha: headSha, event: 'pull_request', created_at: '2026-10-19T04:57:58Z',
    head_repository: { full_name: 'octocat/repo' },
    pull_requests: [{ number: review === 'other-pr' ? 2 : 1 }],
  };
  writeFileSync(ghState, JSON.stringify({
    commits: [DEPENDABOT_COMMIT],
    labels: [],
    bumpPaths: ['package.json', 'package-lock.json'],
    store,
    zip: zip ? zip({ headSha, patch: readIfExists(join(store, String(REVIEW_RUN), 'dep-steward-regenerate', 'regeneration.patch')) }) : undefined,
    reviewRuns: review === 'none' ? [] : [reviewRun],
    runs: {
      [REVIEW_RUN]: {
        status: 'completed',
        jobs: [
          { name: 'review', status: 'completed', conclusion: 'success' },
          { name: 'regenerate', status: 'completed', conclusion: conclusion(regen) },
          { name: 'regenerate-verify', status: 'completed', conclusion: conclusion(verify) },
        ],
      },
    },
    artifactHiddenPolls: inProgress,
    statusInProgressPolls: inProgress,
  }));

  // ---- workflow_run: CI failed, autofix, then the push ----------------------
  const server = await startGitServer(join(root, 'srv'), {});
  try {
    const wrGithub = {
      event_name: 'workflow_run',
      repository: 'octocat/repo',
      event: {
        workflow_run: {
          id: 900, workflow_id: 4242, event: 'pull_request', conclusion: 'failure',
          head_branch: HEAD_BRANCH, head_sha: headSha,
          run_started_at: '2026-10-19T04:58:00Z', created_at: '2026-10-19T04:57:58Z',
        },
        repository: { default_branch: 'main' },
      },
    };
    const secrets = { GITHUB_TOKEN: WORKFLOW_TOKEN, CLAUDE_CODE_OAUTH_TOKEN: 'sk-ant-oat01-test' };
    const wrEnv = (job) => ({
      ...baseEnv,
      RUNNER_TEMP: d(`rt-${job}`),
      DS_JOB: job,
      GITHUB_SHA: headSha,
      GITHUB_SERVER_URL: server.url,
      GITHUB_API_URL,
      EXCHANGE: 'ok',
      OIDC_JWT,
      CLAUDE_APP_TOKEN,
      ...(JOBS[job].permissions?.['id-token'] === 'write'
        ? { ACTIONS_ID_TOKEN_REQUEST_URL: OIDC_REQUEST_URL, ACTIONS_ID_TOKEN_REQUEST_TOKEN: OIDC_REQUEST_TOKEN }
        : {}),
    });
    const autofixTree = checkout('autofix');
    const autofix = await runJob(JOBS, 'autofix', { github: wrGithub, secrets, uses: uses(900), cwd: autofixTree, env: wrEnv('autofix') });
    const handedOver = forgeDecision
      ? { decision: forgeDecision, base_sha: headSha, patch: '' }
      : autofix.outputs;
    if (moveBranch) {
      const mover = checkout('mover');
      git(['config', 'user.email', 'dependabot@example.invalid'], mover);
      git(['config', 'user.name', 'dependabot[bot]'], mover);
      writeFileSync(join(mover, 'package.json'), '{"name":"app","dependencies":{"prisma":"^7.10.1"}}\n');
      git(['commit', '-q', '-am', 'rebase'], mover);
      git(['push', '-q', bare, `HEAD:refs/heads/${HEAD_BRANCH}`], mover);
    }
    const before = git(['--git-dir', bare, 'rev-parse', HEAD_BRANCH]).trim();
    const pushTree = checkout('push');
    git(['remote', 'set-url', 'origin', `${server.url}/octocat/repo.git`], pushTree);
    const push = await runJob(JOBS, 'autofix-push', {
      github: wrGithub, secrets, uses: uses(900), cwd: pushTree, env: wrEnv('autofix-push'),
      needs: { autofix: { outputs: handedOver, result: autofix.failed ? 'failure' : 'success' } },
    });
    const after = git(['--git-dir', bare, 'rev-parse', HEAD_BRANCH]).trim();
    const pushed = after !== before;
    const steps = [regen, verify, autofix, push].flatMap((j) => j.steps);
    return {
      regen, verify, autofix, push, verdict, calls, root, headSha,
      pushed,
      pushedAs: server.seen
        .filter((r) => r.method === 'POST' && r.url.endsWith('/git-receive-pack') && r.status === 200)
        .map((r) => tokenOf(r.auth)),
      pushedFiles: pushed ? git(['--git-dir', bare, 'show', '--name-only', '--format=', HEAD_BRANCH]).split('\n').filter(Boolean) : [],
      pushedNumstat: pushed ? git(['--git-dir', bare, 'show', '--numstat', '--format=', HEAD_BRANCH]).trim() : '',
      comments: readdirSync(comments).sort().map((f) => readFileSync(join(comments, f), 'utf8')),
      npmCalls: readFileSync(npmLog, 'utf8').split('\n').filter(Boolean).map((l) => l.split('\t')),
      ghCalls: readFileSync(ghLog, 'utf8').split('\n').filter(Boolean),
      tokenCalls: readFileSync(curlLog, 'utf8').split('\n').filter(Boolean),
      log: steps.map((s) => `--- ${s.name} [${s.status}]\n${s.output}`).join('\n'),
    };
  } finally {
    await server.close();
  }
}

function readIfExists(f) {
  return existsSync(f) ? readFileSync(f, 'utf8') : '';
}

const labelled = (r) => r.ghCalls.some((c) => /^pr edit 1 --repo octocat\/repo --add-label needs-human-review --add-assignee octocat$/.test(c));

// ---- the #3034 shape ----------------------------------------------------------

let shape3034;
const run3034 = () => (shape3034 ??= runRegeneration());

test('#3034: a bump that leaves the committed client stale is regenerated and pushed as the Claude App, with no agent', async () => {
  const r = await run3034();
  assert.equal(r.verdict, 'verified', r.log);
  assert.equal(r.calls.fixer.length, 0, `the fixer must not run when the regeneration is the fix:\n${r.log}`);
  assert.equal(r.push.failed, false, r.log);
  assert.deepEqual(r.pushedAs, [CLAUDE_APP_TOKEN], `the push must be the App's, so CI runs on it:\n${r.log}`);
  assert.deepEqual(r.pushedFiles.sort(), ['src/generated/prisma/internal/class.ts', 'src/generated/prisma/internal/prismaNamespace.ts']);
  assert.deepEqual(
    r.pushedNumstat.split('\n').map((l) => l.split('\t').slice(0, 2).map(Number)).reduce((n, [a, b]) => n + a + b, 0),
    12,
    'twelve lines, as on #3034: over the agent\'s ten-line budget, and pushed anyway',
  );
  assert.equal(r.comments.length, 1, r.comments.join('\n---\n'));
  assert.match(r.comments[0], /regenerated with `npm run db:generate`: 2 file\(s\), all under src\/generated\/prisma/);
  assert.match(r.comments[0], /CI is now running on the fix/);
});

