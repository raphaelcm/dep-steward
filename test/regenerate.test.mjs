test('an artifact is read as three named entries: a crafted zip writes nothing and pushes only a verified patch for this commit', async () => {
  // The regenerate jobs run the bump's code, so a malicious version can upload
  // any zip under the artifact's name: entries that climb out of the
  // directory, a symlink, a verdict for another commit.
  const craft = (entries, name) => {
    const dir = mkdtempSync(join(tmpdir(), 'ds-zip-'));
    const zip = join(dir, name);
    execFileSync('python3', ['-I', '-c', `
import json, sys, zipfile
entries = json.loads(sys.argv[2])
with zipfile.ZipFile(sys.argv[1], 'w') as z:
    for name, body, link in entries:
        info = zipfile.ZipInfo(name)
        if link:
            info.external_attr = 0o120777 << 16
        z.writestr(info, body)
`, zip, JSON.stringify(entries)]);
    return zip;
  };
  const escapes = [['../../../escaped-by-zip', 'x', false], ['/tmp/ds-absolute-escape', 'x', false], ['link', '/etc', true]];

  const wrongCommit = await runRegeneration({
    zip: ({ patch }) => craft([...escapes, ['verdict', 'verified\n', false], ['head_sha', `${'0'.repeat(40)}\n`, false], ['regeneration.patch', patch, false]], 'a.zip'),
  });
  assert.equal(wrongCommit.pushed, false, wrongCommit.log);
  assert.equal(wrongCommit.calls.fixer.length, 1, 'a verdict for another commit is no verdict: the fixer tries');

  const r = await runRegeneration({
    zip: ({ headSha, patch }) => craft([...escapes, ['verdict', 'verified\n', false], ['head_sha', `${headSha}\n`, false], ['regeneration.patch', patch, false]], 'b.zip'),
  });
  assert.deepEqual(r.pushedAs, [CLAUDE_APP_TOKEN], `the three named entries are all it reads:\n${r.log}`);
  for (const where of [r.root, join(r.root, 'rt-autofix'), join(r.root, 'rt-autofix-push'), tmpdir(), '/tmp']) {
    assert.ok(!existsSync(join(where, 'escaped-by-zip')), `a zip entry escaped to ${where}`);
  }
  assert.ok(!existsSync('/tmp/ds-absolute-escape'));
});

